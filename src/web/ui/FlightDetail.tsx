// Everything about one flight: why it was cleared the way it was, what each
// stage did, how the canary went, what it cost in carbon, and its evidence.

import type { FlightView } from '../../core/projection.ts';
import { STAGES } from '../../core/types.ts';
import type { AgentView } from '../../tower/store.ts';
import type { PolicySummary } from '../state.ts';
import { Bar, ClearanceScale, Empty, LevelChip, PilotMark, Section, StageTrack } from './bits.tsx';
import { STAGE_NAMES, ago, clock, flightStatus, grams, pct } from './format.ts';

export function FlightDetail({ f, agent, policy, onClose }: { f: FlightView; agent?: AgentView; policy: PolicySummary | null; onClose: () => void }) {
  const d = f.decision;
  const report = f.canary?.report;
  return (
    <article className="detail" aria-label={`Flight ${f.id}`}>
      <header className="detail-head">
        <div className="detail-id">
          <span className="detail-call">{f.id}</span>
          <LevelChip level={f.phase === 'go-around' ? 'hold' : f.level} />
          {f.simulated && <span className="sim-flag" title="Generated by the simulator">Simulated</span>}
        </div>
        <button type="button" className="icon-btn" onClick={onClose} aria-label="Close flight details">
          <svg viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M3 3l10 10M13 3 3 13" stroke="currentColor" strokeWidth="1.6" /></svg>
        </button>
      </header>
      <h2 className="detail-title">{f.title}</h2>
      <p className="detail-sub">
        <PilotMark name={f.pilot} />
        {agent && <span className="muted"> · trust {pct(agent.trust)} · {agent.streak} clean landing{agent.streak === 1 ? '' : 's'} in a row</span>}
      </p>
      <p className={`detail-status status-${f.phase}`}>{flightStatus(f)}</p>
      {f.url && (
        <p>
          <a className="link" href={f.url} target="_blank" rel="noreferrer">Open merge request in GitLab</a>
        </p>
      )}

      <Section title="Clearance">
        {d && f.risk ? (
          <>
            <ClearanceScale risk={f.risk.score} allowance={d.thresholds?.autonomous ?? d.allowance} supervised={d.thresholds?.supervised ?? policy?.supervised.maxRisk ?? 0.7} assisted={d.thresholds?.assisted ?? policy?.assisted.maxRisk ?? 0.9} />
            <ul className="reasons">
              {d.reasons.map((r, i) => <li key={i}>{r}</li>)}
            </ul>
            <dl className="facts">
              <div><dt>Pipeline</dt><dd>{d.tier}</dd></div>
              <div><dt>Approvals</dt><dd>{d.approvalsRequired === 0 ? 'none' : d.approvalsRequired}</dd></div>
              <div><dt>Canary plan</dt><dd>{d.canary ? d.canary.steps.map((s) => `${s}%`).join(' · ') : 'no deployment'}</dd></div>
              <div><dt>Bake per step</dt><dd>{d.canary ? `${d.canary.bakeSeconds}s` : '–'}</dd></div>
            </dl>
          </>
        ) : (
          <Empty>The governor issues clearance once the change has been assessed.</Empty>
        )}
      </Section>

      {f.risk && (
        <Section title="Risk" aside={<span className="muted mono">{pct(f.risk.score, 1)} · {f.risk.band}</span>}>
          <ul className="signals">
            {f.risk.signals.map((s) => (
              <li key={s.id}>
                <span className="signal-label">{s.label}</span>
                <Bar value={s.probability} max={0.4} tone={s.id === 'security' ? 'magenta' : 'amber'} label={s.label} />
                <span className="signal-p mono">{pct(s.probability, 1)}</span>
                <span className="signal-detail">{s.detail}</span>
              </li>
            ))}
          </ul>
          <p className="muted small">Signals combine as independent causes: risk = 1 − Π(1 − pᵢ).</p>
        </Section>
      )}

      <Section title="Stages" aside={<StageTrack stages={f.stages} />}>
        <ol className="timeline">
          {STAGES.map((s) => {
            const st = f.stages[s];
            return (
              <li key={s} className={`tl tl-${st.status}`}>
                <span className="tl-dot" aria-hidden="true" />
                <span className="tl-name">{STAGE_NAMES[s]}</span>
                <span className="tl-detail">{st.detail ?? (st.status === 'pending' ? '' : st.status)}</span>
                <span className="tl-time mono">{st.at ? clock(st.at) : ''}</span>
                {st.url && <a className="tl-link" href={st.url} target="_blank" rel="noreferrer">job</a>}
              </li>
            );
          })}
        </ol>
      </Section>

      {(report || f.canary) && (
        <Section title="Canary" aside={report ? <span className={`verdict verdict-${report.verdict}`}>{report.verdict === 'promote' ? 'Promoted' : report.verdict === 'rollback' ? 'Rolled back' : 'Extended'}</span> : <span className="muted mono">{f.canary?.percent}% traffic</span>}>
          {report ? (
            <>
              <div className="canary-compare">
                <div><span className="muted small">Baseline</span><strong className="mono">{pct(report.baseline.errorRate, 2)}</strong><span className="muted small">errors · p95 {report.baseline.p95.toFixed(0)} ms</span></div>
                <div><span className="muted small">Canary</span><strong className="mono">{pct(report.canary.errorRate, 2)}</strong><span className="muted small">errors · p95 {report.canary.p95.toFixed(0)} ms</span></div>
              </div>
              <ul className="checks">
                {report.checks.map((c) => (
                  <li key={c.id} className={c.passed ? 'ok' : 'fail'}>
                    <span className="check-mark" aria-label={c.passed ? 'passed' : 'failed'}>{c.passed ? '✓' : '✕'}</span>
                    {c.summary}
                  </li>
                ))}
              </ul>
            </>
          ) : (
            <p className="muted">Baking at {f.canary?.percent}% of production traffic.</p>
          )}
        </Section>
      )}

      {f.sci && (
        <Section title="Carbon" aside={<span className="mono">{grams(f.sci.sci)} CO₂e</span>}>
          <p className="small">
            {grams(f.sci.sci)} to fly this change from intent to production ({(f.sci.energyKwh * 1000).toFixed(1)} Wh in {f.sci.region}). The risk-adaptive pipeline skipped work worth {grams(f.sci.avoidedG)}, {pct(f.sci.avoidedPct)} of a fixed pipeline.
          </p>
        </Section>
      )}

      {f.evidence && (
        <Section title="Evidence" aside={<span className="muted small">{f.evidence.signed ? 'HMAC-signed' : 'unsigned'}</span>}>
          <p className="small">{f.evidence.records} hash-chained records. Editing any one breaks every hash after it.</p>
          <p className="hash mono">{f.evidence.head.slice(0, 32)}<span className="muted">{f.evidence.head.slice(32)}</span></p>
          <p className="controls">{f.evidence.controls.map((c) => <span key={c} className="control">{c}</span>)}</p>
        </Section>
      )}

      {f.actions.length > 0 && (
        <Section title="Agent activity">
          <ul className="actions">
            {[...f.actions].reverse().map((a, i) => (
              <li key={i}>
                <PilotMark name={a.agent} /> <span>{a.action}</span>
                <span className="muted small"> · {ago(a.at)}</span>
                {a.detail && <span className="action-detail">{a.detail}</span>}
              </li>
            ))}
          </ul>
        </Section>
      )}
    </article>
  );
}
